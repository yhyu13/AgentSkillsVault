# Apply skill tiers to the harnesses that support hiding a skill from the
# model's auto-selection surface.
#
# The vault owns scripts/skill-tiers.txt:
#   A = always model-invocable (description stays in the listing)
#   B = installed, manually invocable, hidden from auto-selection
#   C = vault-only, not installed
#
# Claude Code: tier B becomes skillOverrides[name] = "user-invocable-only",
# which the vendor documents as "Hidden" from Claude's listing but still present
# in the "/" menu. The override lives in the user's settings file, so no skill
# file is touched and the vault copy stays byte-identical to the installed copy.
#
# SAFETY: the settings file may contain a plaintext API token. This script
#   - never prints the file or the parsed object,
#   - never re-serialises it (a text-level insert leaves every other byte alone),
#   - writes UTF-8 without BOM (PowerShell 5.1's Set-Content would add one and
#     break JSON.parse in Claude Code),
#   - backs the file up first, with a name that cannot be picked up as settings,
#   - aborts without writing if the file does not parse.
#
# Usage:
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\apply-tiers.ps1
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\apply-tiers.ps1 -DryRun
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\apply-tiers.ps1 -Remove

param(
  [string]$Vault = (Split-Path -Parent $PSScriptRoot),
  [string]$TierFile = '',
  [switch]$DryRun,
  [switch]$Remove
)

$ErrorActionPreference = 'Stop'
if (-not $TierFile) { $TierFile = Join-Path $Vault 'scripts\skill-tiers.txt' }
$SettingsPath = Join-Path $HOME '.claude\settings.json'
$NoteKey = '__agentSkillsVaultNote'   # legal JSON key; Claude Code ignores unknown keys

# ---- read the tier file ----------------------------------------------------
$tierB = New-Object System.Collections.Generic.List[string]
foreach ($line in (Get-Content -LiteralPath $TierFile -Encoding UTF8)) {
  $l = $line.Trim()
  if (-not $l -or $l.StartsWith('#') -or $l -notmatch '\|') { continue }
  $p = $l -split '\|', 2
  if ($p[1].Trim().ToUpper() -eq 'B') { $tierB.Add($p[0].Trim()) }
}
Write-Host ("Tier B skills (hidden from auto-selection, still invocable): {0}" -f $tierB.Count)

if (-not (Test-Path -LiteralPath $SettingsPath)) {
  Write-Host "No user settings file at $SettingsPath - nothing to apply."
  exit 0
}

$raw = [IO.File]::ReadAllText($SettingsPath, [Text.Encoding]::UTF8)
$hasKey = $raw -match '"skillOverrides"'

if ($Remove) {
  if (-not $hasKey) { Write-Host "No skillOverrides present - nothing to remove."; exit 0 }
  $new = [regex]::Replace($raw, '(?s)"skillOverrides"\s*:\s*\{[^{}]*\}\s*,?', '')
  $new = [regex]::Replace($new, '(?s)"' + $NoteKey + '"\s*:\s*"[^"]*"\s*,?', '')
  try { $null = $new | ConvertFrom-Json } catch { Write-Error "Refusing to write: result does not parse."; exit 1 }
  [IO.File]::WriteAllText($SettingsPath, $new, (New-Object System.Text.UTF8Encoding($false)))
  Write-Host "Removed skillOverrides from the settings file."
  exit 0
}

# ---- build the override object --------------------------------------------
$entries = ($tierB | Sort-Object | ForEach-Object { '    "' + $_ + '": "user-invocable-only"' }) -join ",`n"
$ovText = "`"skillOverrides`": {`n$entries`n  }"
$noteText = "`"$NoteKey`": `"generated by scripts/apply-tiers.ps1 - do not edit by hand`""

# Use a MatchEvaluator so nothing in the replacement is treated as a regex
# substitution pattern.
$evaluator = { param($m) $ovText }
$noteEvaluator = { param($m) $noteText }

if ($hasKey) {
  $new = [regex]::Replace($raw, '(?s)"skillOverrides"\s*:\s*\{[^{}]*\}', $evaluator)
  $new = [regex]::Replace($new, '(?s)"' + $NoteKey + '"\s*:\s*"[^"]*"', $noteEvaluator)
} else {
  # surgical insert right after the opening brace: nothing else in the file moves
  if (-not $raw.TrimStart().StartsWith('{')) {
    Write-Error "Refusing to write: settings.json does not start with '{'."
    exit 1
  }
  # the inserted block is followed by the file's original first key, so it needs
  # a trailing comma - unless the object would otherwise be empty
  $rest = $raw.Substring($raw.IndexOf('{') + 1).Trim()
  $tail = if ($rest -eq '}' -or $rest -eq '') { '' } else { ',' }
  $new = [regex]::Replace($raw, '^\s*\{', { param($m) "{`n  $ovText,`n  $noteText$tail" })
}

try { $null = $new | ConvertFrom-Json } catch { Write-Error "Refusing to write: the result does not parse as JSON. Nothing was changed."; exit 1 }

if ($DryRun) {
  Write-Host "Dry run: would write $([System.Text.Encoding]::UTF8.GetByteCount($new)) bytes to $SettingsPath (no change made)."
  exit 0
}

$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$backup = "$SettingsPath.vaultbak-$stamp"
Copy-Item -LiteralPath $SettingsPath -Destination $backup -Force
[IO.File]::WriteAllText($SettingsPath, $new, (New-Object System.Text.UTF8Encoding($false)))

# prove the change is additive: only the managed block was added
$before = (Get-Content -LiteralPath $backup -Raw -Encoding UTF8).Split("`n").Count
$after  = (Get-Content -LiteralPath $SettingsPath -Raw -Encoding UTF8).Split("`n").Count
Write-Host ("Applied {0} tier-B overrides to {1}" -f $tierB.Count, $SettingsPath)
Write-Host ("Backup: {0}  (lines {1} -> {2})" -f $backup, $before, $after)
Write-Host "Undo: restore the backup over the settings file, or re-run with -Remove."
