# -*- coding: utf-8 -*-
"""Build the reel timeline + final audio track.

1. Read reel/audio/timings.json (real TTS durations).
2. Lay segments on one timeline with fixed gaps.
3. Decode each mp3 to wav, place into a mono 44.1k buffer.
4. Synthesize a soft pad bed with numpy (no external deps).
5. Mix, write reel/audio/final.wav and reel/timeline.js for the page.
"""
import json
import os
import subprocess
import wave

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
AUD = os.path.join(ROOT, "reel", "audio")
SR = 44100
LEAD_IN = 1.4
GAP = 0.55
TAIL = 2.6


def ffmpeg():
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


def decode(path):
    """mp3 -> float32 mono at SR."""
    tmp = path + ".tmp.wav"
    subprocess.run([ffmpeg(), "-y", "-i", path, "-ac", "1", "-ar", str(SR), tmp],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    with wave.open(tmp, "rb") as w:
        raw = w.readframes(w.getnframes())
    os.remove(tmp)
    return np.frombuffer(raw, dtype="<i2").astype(np.float32) / 32768.0


def pad_bed(total, t_segments):
    """Soft pad: slow chord bed that ducks under speech, plus a faint pulse."""
    n = int(total * SR)
    t = np.arange(n) / SR
    out = np.zeros(n, dtype=np.float32)

    # Am9 - Fmaj7 - Cmaj7 - G6 loop, 8s per chord
    chords = [
        [220.00, 261.63, 329.63, 493.88],   # A3 C4 E4 B4
        [174.61, 220.00, 261.63, 329.63],   # F3 A3 C4 E4
        [130.81, 196.00, 261.63, 329.63],   # C3 G3 C4 E4
        [196.00, 246.94, 293.66, 392.00],   # G3 B3 D4 G4
    ]
    bar = 8.0
    for ci, chord in enumerate(chords):
        start = ci * bar
        for k in range(0, int(total / (bar * len(chords))) + 2):
            s0 = start + k * bar * len(chords)
            s1 = s0 + bar + 1.6            # overlap for legato
            i0, i1 = int(s0 * SR), min(n, int(s1 * SR))
            if i0 >= n:
                continue
            seg = t[i0:i1] - s0
            env = np.minimum(1.0, seg / 1.4) * np.minimum(1.0, np.maximum(0.0, (s1 - s0 - seg) / 1.6))
            for f in chord:
                for det, amp in ((1.0, 0.5), (1.0035, 0.28), (0.9965, 0.28)):
                    out[i0:i1] += (amp * 0.055) * env * np.sin(2 * np.pi * f * det * seg)

    # sub pulse on the half bar, very quiet, gives the bed a heartbeat
    beat = 4.0
    for k in range(int(total / beat) + 1):
        s0 = k * beat
        i0, i1 = int(s0 * SR), min(n, int((s0 + 1.1) * SR))
        if i0 >= n:
            continue
        seg = t[i0:i1] - s0
        out[i0:i1] += 0.05 * np.exp(-seg * 3.2) * np.sin(2 * np.pi * 55 * seg)

    # duck the bed while someone is speaking
    duck = np.ones(n, dtype=np.float32)
    for s, e in t_segments:
        i0, i1 = int(s * SR), min(n, int((e + 0.25) * SR))
        duck[i0:i1] *= 0.55
    # smooth the ducking envelope
    k = int(0.25 * SR)
    kernel = np.ones(k, dtype=np.float32) / k
    duck = np.convolve(duck, kernel, mode="same")
    return out * duck


def main():
    spec = json.load(open(os.path.join(AUD, "timings.json"), encoding="utf-8"))
    segs = spec["segments"]

    cursor = LEAD_IN
    placed = []
    for s in segs:
        placed.append({"id": s["id"], "chapter": s["chapter"], "text": s["text"],
                       "start": round(cursor, 3), "end": round(cursor + s["duration"], 3),
                       "duration": s["duration"]})
        cursor += s["duration"] + GAP
    total = round(cursor - GAP + TAIL, 3)

    n = int(total * SR)
    voice = np.zeros(n, dtype=np.float32)
    for item in placed:
        a = decode(os.path.join(AUD, "narration", item["id"] + ".mp3"))
        i0 = int(item["start"] * SR)
        i1 = min(n, i0 + len(a))
        voice[i0:i1] += a[: i1 - i0]

    bed = pad_bed(total, [(p["start"], p["end"]) for p in placed])
    mix = voice + bed * 0.85

    peak = float(np.max(np.abs(mix)))
    if peak > 0:
        mix = mix * (0.92 / peak)
    pcm = (np.clip(mix, -1, 1) * 32767).astype("<i2")

    wav_path = os.path.join(AUD, "final.wav")
    with wave.open(wav_path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())

    mp3_path = os.path.join(AUD, "final.mp3")
    subprocess.run([ffmpeg(), "-y", "-i", wav_path, "-c:a", "libmp3lame", "-b:a", "160k", mp3_path],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    timeline = {"total": total, "fps": 30, "width": 1920, "height": 1080,
                "leadIn": LEAD_IN, "gap": GAP, "tail": TAIL, "segments": placed}
    with open(os.path.join(ROOT, "reel", "timeline.json"), "w", encoding="utf-8") as f:
        json.dump(timeline, f, ensure_ascii=False, indent=2)

    js = "// generated by source/build_audio.py — do not edit\nwindow.TIMELINE = %s;\n" % json.dumps(
        timeline, ensure_ascii=False, indent=2)
    with open(os.path.join(ROOT, "reel", "timeline.js"), "w", encoding="utf-8") as f:
        f.write(js)

    print("total=%.2fs wav=%.1fMB mp3=%.1fMB" % (
        total, os.path.getsize(wav_path) / 1e6, os.path.getsize(mp3_path) / 1e6))
    for p in placed:
        print("  %s %6.2f -> %6.2f  %s" % (p["id"], p["start"], p["end"], p["chapter"]))


if __name__ == "__main__":
    main()
